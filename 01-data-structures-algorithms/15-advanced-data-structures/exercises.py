# 15 Advanced Data Structures Practice Questions
# Question-only exercises. No solutions included.

# Question 1:
# Design a trie that stores words and supports insert and search operations efficiently.

# Question 2:
# Implement a union-find structure that supports union and find operations with path compression.

# Question 3:
# Build a segment tree that can answer range sum queries and update a single element efficiently.

# Question 4:
# Design a least recently used cache with O(1) eviction and retrieval operations.

# Question 5:
# Given a set of integers, implement a Fenwick tree to support prefix sum queries and point updates.

# Question 6:
# Build a balanced binary search tree variant or explain why a simple BST can degrade without balancing.

# Question 7:
# Design a skip list or explain how a probabilistic structure can support fast search and insertion.

# Question 8:
# Explain the trade-offs among arrays, hash maps, tries, heaps, trees, and graphs when solving a problem that has many repeated queries or updates.
