# 12 Graphs Practice Questions
# Question-only exercises. No solutions included.

# Question 1:
# Given an undirected graph, perform a depth-first search and explain the visited-state logic.

# Question 2:
# Given a graph with nodes and edges, determine whether the graph is connected and whether it contains a cycle.

# Question 3:
# Find the shortest path from a source node to all other nodes in an unweighted graph.

# Question 4:
# Given a directed graph, determine whether it is possible to finish all tasks in order without violating dependencies.

# Question 5:
# Find the minimum spanning tree of a connected weighted graph using a greedy strategy.

# Question 6:
# Given a graph, determine whether there is a path from the source to the destination avoiding blocked cells or nodes.

# Question 7:
# Solve the problem of finding the number of connected components in a graph using iterative or recursive traversal.

# Question 8:
# Compare BFS and DFS in terms of traversal order, queue vs stack usage, and the kinds of problems each is best suited to.
